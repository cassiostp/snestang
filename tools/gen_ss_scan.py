#!/usr/bin/env python3
"""Generate byte scan hooks and the unchanged sparse-image address map.

The original feature revision is the schema. Only full bytes enter a chain;
partial fields and externally visible video/audio outputs keep their byte hooks.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = '292d641'
CONFIG = [('ppu.v', 0x1bf0, {'COLOR_OUT', 'D_OUT', 'H_CNT', 'V_CNT', 'OUT_X', 'OUT_Y'}),
          ('dsp.v', 0x1bf2, {'AUDIO_L', 'AUDIO_R'}),
          ('cpu.v', 0x1bf4, {'WRIO'})]
image = json.loads(subprocess.check_output(['git', 'show', SCHEMA+':src/ss_map.json'], cwd=ROOT))
all_nodes = []
ends = []
for name, command, excluded in CONFIG:
    text = subprocess.check_output(['git', 'show', SCHEMA+':src/'+name], cwd=ROOT, text=True)
    oracle = text[text.rindex('// Register image;'):text.rindex('\n`endif\nendmodule')]
    oracle = 'reg [7:0] ss_legacy_q;\n'+oracle.replace('ss_q', 'ss_legacy_q')
    # Child/RAM readback names remain the original wires.
    for suffix in ['_cg','_oa','_p65','_ce']:
        oracle=oracle.replace('ss_legacy_q'+suffix,'ss_q'+suffix)
    (ROOT/'sim/savestate'/('legacy_'+name[:-2]+'_read.vh')).write_text(oracle+'\n')
    scalar = {int(a,16) for a in re.findall(r"13'h([0-9a-f]+): ss_q =", text)}
    writes = {int(a,16): lhs.strip() for a,lhs in re.findall(
        r"13'h([0-9a-f]+):\s*([^;\n]+?)\s*<=\s*ss_d(?:\[[^]]+\])?;",text)}
    if name == 'dsp.v': writes[0x1006] = 'regram_saved'
    nodes = [e for e in image[name] if e['address'] in scalar and e['bits']==8
             and e['expression'].split('[')[0] not in excluded]
    for e in nodes:
        assert e['address'] in writes, (name,e)
        e['target'] = writes[e['address']]
    successor = {e['address']: (nodes[i+1]['target'] if i+1<len(nodes) else
                               f"(ss_a[0] ? ss_d : {nodes[0]['target']})")
                 for i,e in enumerate(nodes)}
    selected = {e['address'] for e in nodes}
    def rewrite(m):
        body=m[1]
        found=[int(a,16) for a in re.findall(r"13'h([0-9a-f]+):\s*[^;\n]+?\s*<=\s*ss_d",body) if int(a,16) in selected]
        if not found:return m[0]
        assigns=[]
        for a in found:
            pat=rf"[ \t]*13'h{a:04x}:\s*([^;\n]+?)\s*<=\s*ss_d(?:\[[^]]+\])?;\n"
            body,n=re.subn(pat,'',body)
            assert n==1,(name,hex(a),n)
            assigns.append(f"          {writes[a]} <= {successor[a]};")
        branch=f"        13'h{command:04x}, 13'h{command+1:04x}: begin\n"+'\n'.join(assigns)+'\n        end\n'
        return 'case (ss_a)'+body+branch+'      endcase'
    # Read cases do not contain nonblocking assignments and must not be rewritten.
    text=re.sub(r'case \(ss_a\)(.*?)endcase',rewrite,text,flags=re.S)
    if name=='dsp.v':
        old="if (ss_we && ss_a == 13'h1006) regram_saved <= ss_d;"
        new=(f"if (ss_we && (ss_a == 13'h{command:04x} || ss_a == 13'h{command+1:04x}))\n"
             f"        regram_saved <= {successor[0x1006]};")
        assert old in text
        text=text.replace(old,new)
    # Delete selected scalar read cases. RAM and nested-module readbacks remain.
    for a in selected:
        text,n=re.subn(rf"    13'h{a:04x}: ss_q = [^;]+;\n",'',text)
        assert n==1,(name,hex(a),n)
    pos=text.rindex('\nend\n`endif\nendmodule')
    serial=(f"\n    // Scan data is visible only during an internal write command.\n"
            f"    if (ss_we && (ss_a == 13'h{command:04x} || ss_a == 13'h{command+1:04x}))\n"
            f"        ss_q = {nodes[0]['target']};")
    text=text[:pos]+serial+text[pos:]
    pos=text.rindex('\n`endif\nendmodule')
    verification='\n`ifdef SS_SCAN_VERIFY\n`include \"legacy_'+name[:-2]+'_read.vh\"\n`endif\n'
    text=text[:pos]+verification+text[pos:]
    (ROOT/'src'/name).write_text(text)
    for e in nodes:all_nodes.append(dict(module=name,address=e['address'],target=e['target']))
    ends.append(len(all_nodes)-1)
    print(name,len(nodes),'full bytes')
assert len(all_nodes)<512

def compact(a):
    if a<0x200:return a
    if 0x1000<=a<0x10ee:return 0x200+(a-0x1000)
    if 0x116e<=a<0x1172:return 0x2ee+(a-0x116e)
    if 0x1600<=a<0x1700:return 0x300+(a-0x1600)
    raise ValueError(hex(a))

lines=['// Generated by tools/gen_ss_scan.py; sparse image offsets remain version 1.',
       f"localparam [8:0] SCAN_LAST = 9'd{len(all_nodes)-1};",
       'function [12:0] scan_command(input [8:0] a, input loading);',
       '    begin',
       f"        if (a <= 9'd{ends[0]}) scan_command = 13'h1bf0 + loading;",
       f"        else if (a <= 9'd{ends[1]}) scan_command = 13'h1bf2 + loading;",
       "        else scan_command = 13'h1bf4 + loading;",'    end','endfunction',
       'function scan_range(input [12:0] a);',
       "    scan_range = a < 13'h0200 || (a >= 13'h1000 && a < 13'h10ee) ||",
       "                 (a >= 13'h116e && a < 13'h1172) || (a >= 13'h1600 && a < 13'h1700);",
       'endfunction', 'function [9:0] scan_lookup_addr(input [12:0] a);',
       "    if (a < 13'h0200) scan_lookup_addr = a[9:0];",
       "    else if (a >= 13'h116e && a < 13'h1172) scan_lookup_addr = 10'h2ee + (a - 13'h116e);",
       "    else if (a[12:8] == 5'h10) scan_lookup_addr = {2'b10, a[7:0]};",
       "    else scan_lookup_addr = {2'b11, a[7:0]};",'endfunction',
       'reg [8:0] scan_map [0:1023] /* synthesis syn_ramstyle = "block_ram" */;',
       'reg [8:0] scan_map_q;', 'integer scan_init;', 'initial begin',
       "    for (scan_init=0; scan_init<1024; scan_init=scan_init+1) scan_map[scan_init] = 0;"]
seen=set()
for i,e in enumerate(all_nodes):
    a=compact(e['address']);assert a not in seen;seen.add(a)
    lines.append(f"    scan_map[10'h{a:03x}] = 9'd{i+1};")
lines+=['end','always @(posedge clk)',
        '    scan_map_q <= scan_map[scan_lookup_addr(img_wr_stb ?',
        "        (img_waddr[12:0] - 13'd512) : (img_raddr[12:0] - 13'd512))];",'']
(ROOT/'src/ss_scan_map.vh').write_text('\n'.join(lines))
(ROOT/'src/ss_scan_map.json').write_text(json.dumps(all_nodes,indent=2)+'\n')
print('total',len(all_nodes),'bytes; chain ends',ends)
